CREATE TABLE batch_runs (
    id bigint NOT NULL,
    ended_at timestamp(6) with time zone,
    host character varying(255),
    job_name character varying(255),
    orders_read integer,
    started_at timestamp(6) with time zone,
    status character varying(255)
);

ALTER TABLE batch_runs ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME batch_runs_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE idempotency_keys (
    id character varying(255) NOT NULL,
    actor_id uuid,
    created_at timestamp(6) with time zone,
    fingerprint character varying(512),
    idem_key character varying(128),
    response_body text,
    response_status integer
);

CREATE TABLE job_leases (
    name character varying(100) NOT NULL,
    owner character varying(200) NOT NULL,
    lease_until timestamp with time zone NOT NULL
);

CREATE TABLE notifications (
    id uuid NOT NULL,
    created_at timestamp(6) with time zone,
    order_id uuid,
    recipient character varying(255),
    type character varying(255)
);

CREATE TABLE order_lines (
    id bigint NOT NULL,
    product_name character varying(255),
    quantity integer NOT NULL,
    sku character varying(255),
    unit_price numeric(12,2),
    order_id uuid
);

ALTER TABLE order_lines ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
